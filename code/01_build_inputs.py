def dump(name, table, header, fmt):
    rows = []
    for y in sorted(table):
        assert len(table[y]) == 12, (name, y)
        for m, v in enumerate(table[y], 1):
            if v is None and not (name == "us3m" and (y, m) == (2020, 4)):
                continue
            rows.append((f"{y}-{m:02d}", "" if v is None else fmt % v))
    with open(os.path.join(OUT, name + ".csv"), "w", newline="") as f:
        w = csv.writer(f); w.writerow(["month", header]); w.writerows(rows)
    return len(rows)

